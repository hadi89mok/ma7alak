-- Public module also watches shop_profiles for Admin ON/OFF.
-- -----------------------------------------------------------------
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname='supabase_realtime'
      and schemaname='public'
      and tablename='shop_catalogs'
  ) then
    alter publication supabase_realtime add table public.shop_catalogs;
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname='supabase_realtime'
      and schemaname='public'
      and tablename='shop_profiles'
  ) then
    alter publication supabase_realtime add table public.shop_profiles;
  end if;
end;
$$;

