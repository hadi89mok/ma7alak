-- -----------------------------------------------------------------
-- Catalog image Storage policy.
-- Images live in shop-gallery/owner-catalog/<shop_slug>/...
-- -----------------------------------------------------------------
drop policy if exists "Owners can upload catalog images"
  on storage.objects;

create policy "Owners can upload catalog images"
on storage.objects
for insert
to authenticated
with check (
  bucket_id='shop-gallery'
  and (storage.foldername(name))[1]='owner-catalog'
  and public.owner_has_shop_option(
    (storage.foldername(name))[2],
    'catalog_enabled'
  )
  and public.owner_has_shop_option(
    (storage.foldername(name))[2],
    'catalog_images_enabled'
  )
);

drop policy if exists "Owners can delete catalog images"
  on storage.objects;

create policy "Owners can delete catalog images"
on storage.objects
for delete
to authenticated
using (
  bucket_id='shop-gallery'
  and (storage.foldername(name))[1]='owner-catalog'
  and exists (
    select 1
    from public.shop_owners o
    where o.user_id=(select auth.uid())
      and o.shop_slug=(storage.foldername(name))[2]
  )
);

